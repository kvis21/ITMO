\ Объявляем глобальные переменные в Data Memory
VARIABLE IS-DONE

\ Pascal-строка: первый элемент (машинное слово) — длина, далее сами символы
\ Конструкция P"" размещает строку в Data Memory и возвращает ее адрес
: MSG_END P"Done!" ;

\ Процедура вывода Pascal-строки в порт вывода (например, порт 2)
: PRINT-PSTR ( addr -- )
  DUP @                 \ Читаем длину строки. Стек: addr len
  SWAP 1 + SWAP         \ Сдвигаем указатель на начало данных. Стек: data_addr len
  
  BEGIN
    DUP 0 >             \ Пока len > 0
  WHILE
    OVER @ 2 OUT        \ Читаем символ по data_addr и пишем в порт 2
    SWAP 1 + SWAP       \ Инкрементируем data_addr
    1 -                 \ Декрементируем len
  REPEAT
  DROP DROP             \ Очищаем стек
;

\ Обработчик прерываний (Interrupt Service Routine)
\ Вызывается аппаратно, когда приходит символ по расписанию
: RX-ISR
  1 IN                  \ Читаем символ из порта ввода (порт 1)
  DUP 113 = IF          \ Если символ равен 'q' (ASCII 113)
    1 IS-DONE !         \ Записываем 1 в переменную IS-DONE
    DROP                \ Очищаем символ со стека
  ELSE
    2 OUT               \ Иначе выводим символ в порт вывода (порт 2)
  THEN
  IRET                  \ Специальная инструкция возврата из прерывания
;

\ Процедура высшего порядка для демонстрации Execution Token
\ Принимает адрес строки и Execution Token функции печати, затем вызывает её
: EXEC-PRINT ( addr xt -- )
  EXECUTE               \ Вызывает то, чей токен лежит на вершине стека
;

\ Точка входа
: MAIN
  0 IS-DONE !           \ Инициализируем флаг
  
  \ Регистрируем обработчик прерывания
  \ ' (tick) берет Execution Token следующего слова
  ' RX-ISR 0 SET-ISR    \ Устанавливаем RX-ISR на 0-й вектор прерывания
  
  EI                    \ Enable Interrupts (разрешаем прерывания)
  
  \ Бесконечный цикл ожидания (idle loop), пока прерывание не изменит IS-DONE
  BEGIN
    IS-DONE @
  UNTIL                 \ UNTIL выходит из цикла, если на вершине стека не 0
  
  DI                    \ Disable Interrupts (запрещаем прерывания перед выходом)
  
  \ Передаем адрес строки и токен функции печати
  MSG_END ' PRINT-PSTR EXEC-PRINT
;